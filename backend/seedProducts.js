async function seedProducts() {
  try {
    if (!process.env.MONGODB_URI) {
      throw new Error("MONGODB_URI missing in backend/.env");
    }

    await mongoose.connect(process.env.MONGODB_URI);

    // Insert only products whose names do not already exist.
    // Existing products and orders are not deleted.
    let added = 0;

    for (const item of products) {
      const exists = await Product.findOne({ name: item.name });

      if (!exists) {
        await Product.create({
          ...item,
          title: item.name,
          description:
            `${item.name}. Demo catalogue item. Verify actual weight, purity, ` +
            "stone certification, current metal rate and final price before sale.",
          images: [item.image],
          stock: 10,
          isActive: true,
        });

        added++;
      }
    }

    const total = await Product.countDocuments();

    console.log(`Seed complete. New products added: ${added}`);
    console.log(`Total products in database: ${total}`);
  } catch (error) {
    console.error("Seed failed:", error.message);
  } finally {
    await mongoose.disconnect();
  }
}

seedProducts();
